export function ti(template: string, vars: Record<string, string>): string {
  // Accept both {{var}} and {var} — several shipped strings use single braces.
  let out = template
  for (const [k, v] of Object.entries(vars)) {
    out = out.split('{{' + k + '}}').join(v).split('{' + k + '}').join(v)
  }
  return out
}

export function t(lang: Language, key: TranslationKey): string {
  return translations[lang][key] || translations.en[key] || key
}

// BCP-47 locale for toLocaleDateString/toLocaleTimeString per app language
export function localeFor(lang: Language): string {
  return lang === 'es' ? 'es-MX' : lang === 'pt' ? 'pt-BR' : 'en-US'
}

// Static translator for lib code that runs outside React (permissions
// prompts, background tasks). Cache updated by getLanguage/setLanguage, so
// after app boot it always reflects the user's choice; 'en' only before the
// first load resolves.
let cachedLang: Language = 'en'
export function tStatic(key: TranslationKey): string {
  return t(cachedLang, key)
}

export async function getLanguage(): Promise<Language> {
  try {
    const lang = await AsyncStorage.getItem('language')
    if (lang === 'en' || lang === 'es' || lang === 'pt') {
      cachedLang = lang
      return lang
    }
    return 'en'
  } catch {
    return 'en'
  }
}

export async function setLanguage(lang: Language): Promise<void> {
  cachedLang = lang
  await AsyncStorage.setItem('language', lang)
}
